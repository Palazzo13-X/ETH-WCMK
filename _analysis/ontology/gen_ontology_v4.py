def parse_narrative(case):
    """Pull the typed entities out of the layer-B narrative (they are structured text)."""
    text = case.get("narrative", "")
    stakeholders, consequence, evidence, vulnerability, review_body, prior, objective, resources, mitigation = [], [], [], [], None, None, None, None, None
    parts = text.split(". ")
    for part in parts:
        if part.startswith("Those affected include "):
            chunk = part[len("Those affected include "):]
            stake, _, vuln = chunk.partition("; ")
            stakeholders = [s.strip() for s in stake.split(",") if s.strip()]
            if vuln:
                vulnerability = vuln.rstrip(".")
        elif "the most plausible consequence is " in part:
            consequence = part.split("the most plausible consequence is ", 1)[1].split(", materialising")[0].strip()
        elif "Regarding the agent's conduct: " in part:
            chunk = part.split("Regarding the agent's conduct: ", 1)[1]
            good, _, rest = chunk.partition(". However, ")
            evidence.append((good.strip(), "present"))
            if rest:
                evidence.append((rest.rstrip(".").split(", and ")[0].strip(), "absent"))
        elif "The instruments invoked by the review are " in part:
            chunk = part.split("The instruments invoked by the review are ", 1)[1]
            _, _, rev = chunk.partition(", while ")
            review_body = rev.rstrip(".")
        elif "the institutional record in this area reports that " in part:
            prior = part.split("the institutional record in this area reports that ", 1)[1].rstrip(".")
        elif "The declared purpose of the deployment is to " in part:
            objective = part.split("The declared purpose of the deployment is to ", 1)[1].rstrip(".")
        elif "The operating conditions are constrained: " in part:
            chunk = part.split("The operating conditions are constrained: ", 1)[1]
            res, _, mit = chunk.partition(", and ")
            resources = res.strip()
            mitigation = mit.rstrip(".")
        elif "The case displays a " in part and " tension: " in part:
            ambiguity = part.split(" tension: ", 1)[1].rstrip(".")
            case["_ambiguity"] = ambiguity
    return stakeholders, consequence, evidence, vulnerability, review_body, prior, objective, resources, mitigation




