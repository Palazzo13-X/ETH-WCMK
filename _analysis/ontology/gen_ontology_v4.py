def emit_facets():
    out = [head("02_facets - the 28 canonical facets, read from facet_registry.py")]
    for code, cls in (("W", "WantFacet"), ("C", "CanFacet"), ("M", "MustFacet"), ("K", "KnowFacet")):
        out.append(f"eth:{cls} rdfs:subClassOf eth:Facet .")
    out.append("eth:GuardedFacet rdfs:subClassOf eth:Facet .")
    for f in FACETS:
        types = f"fac:{f.code} a eth:Facet, eth:{PILLAR_OF[f.primary_pillar()]}Facet"
        if f.guard:
            types += ", eth:GuardedFacet"
        parts = [types + " ;"]
        parts.append(f"  eth:code {q(f.code)} ;")
        parts.append(f"  rdfs:label {q(f.label)} ;")
        for i, b in enumerate(f.beta):
            parts.append(f"  eth:beta{PILLARS[i]} {num(b)} ;")
        parts.append(f"  eth:betaSum {num(sum(f.beta))} ;")
        parts.append(f"  eth:nPillars {f.n_pillars()} ;")
        nz = [b for b in f.beta if b > 0]
        parts.append(f"  eth:minNonZeroBeta {num(min(nz))} ;")
        parts.append(f"  eth:primaryPillar eth:pillar_{f.primary_pillar()} ;")
        pillars = ", ".join(f"eth:pillar_{p}" for p, b in zip(PILLARS, f.beta) if b > 0)
        parts.append(f"  eth:sharesPillar {pillars} ;")
        parts.append(f"  eth:aggregationPolicy eth:Policy_{f.policy} ;")
        parts.append(f"  eth:hardGuard {num(f.guard)} ;")
        parts.append(f"  eth:guardMin {num(f.guard_min)} ;")
        parts.append(f"  eth:source {q(f.source)} ;")
        parts.append(f"  eth:observable {q(f.observable)} ;")
        crit = " ,\n    ".join(f"[ a eth:CriticalityStatement ; eth:criticalityDomain eth:domain_{d} ; "
                              f"eth:criticalityLevel {f.criticality[d]} ]"
                               for d in DOMAINS)
        parts.append(f"  eth:criticalityStatement\n    {crit} .")
        out.append("\n".join(parts))
    return "\n".join(out) + "\n"


