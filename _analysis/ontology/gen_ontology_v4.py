def emit_chain(out, cid, layer_profiles, spec, cal, stats):
    order = ("model", "system", "operator")
    per_layer = []
    for layer in order:
        prof = layer_profiles[layer]
        ref = confront(spec, prof, cal, FACETS)
        low = _adequacy(spec, prof, cal, FACETS, "pessimistic")
        assert abs(round(low["aa"], 4) - ref["adequacy_decision"]) < 1e-9, (cid, layer)
        assert abs(round(low["R_r"], 4) - ref["R_r"]) < 1e-9, (cid, layer)
        per_layer.append({"layer": layer, "decision": ref["decision"],
                         "adequacy_low": low["aa"], "R_r": low["R_r"],
                         "abstention": ref["epistemic_abstention"]})
    res = confront_chain(spec, [layer_profiles[l] for l in order], cal, FACETS)
    live = [x for x in per_layer if x["decision"] != "ABSTAIN"]
    pool = live or per_layer
    weakest = min(pool, key=lambda x: round(x["adequacy_low"], 4))
    assert res["decision"] == weakest["decision"] or not live, (cid, res["decision"], weakest)
    individual(out, "cse:CHAIN_" + cid, ["eth:ConfrontationChain"],
               [("rdfs:label", q("layered agency of " + cid)),
                ("eth:chainCase", "cse:" + cid),
                ("eth:weakestLinkLayer", "eth:Layer_" + weakest["layer"]),
                ("eth:chainDecision", "eth:Decision_" + res["decision"]),
                ("eth:chainAdequacyLow", num(weakest["adequacy_low"])),
                ("eth:chainResidualRisk", num(max(x["R_r"] for x in pool))),
                ("eth:chainEpistemicAbstention", num(all(x["abstention"] for x in per_layer))),
                ("eth:fallbackForChain", "eth:Fallback_human_review"),
                ("eth:delegationChain", "ag:chain_" + cid + "_d3"),
                ("eth:layerResult", bnode_list([
                    ["a eth:ChainLayerResult",
                     "eth:resultLayer eth:Layer_" + x["layer"],
                     f"eth:resultAdequacyLow {num(x['adequacy_low'])}",
                     "eth:resultDecision eth:Decision_" + x["decision"],
                     f"eth:resultResidualRisk {num(x['R_r'])}"]
                    for x in per_layer]))])
    emit_delegation(out, cid, spec.critical_pillars, stats)


