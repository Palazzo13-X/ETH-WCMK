def build_conflicts():
    conflicts = []
    n = 0
    for d in DOMAINS:
        inst_codes = [c for c, lbl, klass, ds, norms in INSTRUMENTS if d in ds]
        for pattern, desc, k1, p1, k2, p2, strategy, rank in PATTERNS:
            a = b = None
            for c in inst_codes:
                norms = [x for x in INSTRUMENTS if x[0] == c][0][4]
                for i, (kind, pillar, statement, rnk, defeas, facet) in enumerate(norms):
                    nid = f"{c}_{kind[0]}{i+1}"
                    if kind == k1 and pillar == p1 and a is None:
                        a = nid
                    elif kind == k2 and pillar == p2 and b is None and nid != a:
                        b = nid
            if a is None or b is None:
                continue
            n += 1
            status = ("unresolved_escalation"
                      if strategy in ("Strategy_escalation", "Strategy_abstention") else "resolved")
            conflicts.append((n, pattern, a, b, strategy, rank, d, status, p1, p2))
    return conflicts


