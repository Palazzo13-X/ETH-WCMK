def head(title):
    lines = ["# " + title,
             "# Generated by _analysis/ontology/gen_ontology_v4.py - do not hand-edit.",
             "# Source of truth: _analysis/formal_core/facet_registry.py and core.py."]
    lines += [f"@prefix {k}: <{v}> ." for k, v in PREFIXES.items()]
    return "\n".join(lines) + "\n"


def num(x):
    """Turtle numeric literal. Floats are emitted as explicitly typed xsd:double:
    a bare `0.3` in Turtle is an xsd:decimal and `0` an xsd:integer, both of which the
    shapes' `sh:datatype xsd:double` constraints reject (defect fixed in v4.1)."""
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, int):
        return str(x)
    return f'"{float(x):.12g}"^^xsd:double'


def esc(s):
    return str(s).replace("\\", "\\\\").replace('"', '\\"')


def q(s):
    return f'"{esc(s)}"'


def pcls(name, comment=None, supercls=None):
    out = [f"eth:{name} a owl:Class ; rdfs:label {q(name)} ."]
    if supercls:
        out.append(f"eth:{name} rdfs:subClassOf eth:{supercls} ; rdfs:comment {q(comment or '')} .")
    elif comment:
        out.append(f"eth:{name} rdfs:comment {q(comment)} .")
    return "\n".join(out)


def prop(name, kind, domain, rng, comment="", functional=False, transitive=False,
         inverse=None):
    types = ["owl:ObjectProperty" if kind == "object" else "owl:DatatypeProperty"]
    if functional:
        types.append("owl:FunctionalProperty")
    if transitive:
        types.append("owl:TransitiveProperty")
    line = f"eth:{name} a " + ", ".join(types) + " ;"
    line += f" rdfs:label {q(name)} ;"
    line += " rdfs:domain " + (domain if ":" in domain else "eth:" + domain) + " ;"
    line += " rdfs:range " + (rng if ":" in rng else "eth:" + rng) + " ;"
    if inverse:
        line += f" owl:inverseOf eth:{inverse} ;"
    if comment:
        line += f" rdfs:comment {q(comment)}"
    return line + " ."


def disjoint(names):
    out = []
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            out.append(f"eth:{names[i]} owl:disjointWith eth:{names[j]} .")
    return "\n".join(out)


