#!/usr/bin/env python3
"""Build a stratified, self-contained slice of the v4 instance graph (G4' helper).

Why: the machine has ~2 GB free while the local inference engine is resident.
Parsing the whole 1,893,019-triple graph (peak RSS ~2.2 GB) and running pyshacl
over it is not survivable in the current environment. The slice keeps the
validation meaningful rather than token: it is closed under the classes the
shapes target and covers every domain, layer and persona archetype in the corpus.

Selection rule (deterministic, no RNG):
  * N_CASES cases picked by round-robin over the (layer, domain) cells;
  * every block whose subject is one of those cases, or whose block text
    references one of them (profiles, confrontations, chains, links,
    consequences, evidence, stakeholders);
  * every Agent block (personas are shared across cases and the retained
    profiles point at them).

Writes Ontologias/ontology_v4/fixtures/instances_subset.ttl and the report
Evaluacoes/r4/ontology_subset_stats.json.
"""
import json
import os
import re
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ONT = os.path.join(ROOT, "Ontologias", "ontology_v4")
SRC = os.path.join(ONT, "fixtures", "instances.ttl")
OUT = os.path.join(ONT, "fixtures", "instances_subset.ttl")
STATS = os.path.join(ROOT, "Evaluacoes", "r4", "ontology_subset_stats.json")
N_CASES = 120
CASE_RE = re.compile(r"ETHCASE-([A-Z])-(\d{4})")


def prefixes():
    out = []
    with open(SRC, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("@prefix"):
                out.append(line)
            elif line.strip() and not line.startswith("#"):
                break
    return "".join(out)


def blocks_of(path):
    """Split the TTL into subject blocks: a block starts at column 0 and ends at
    the line whose last character is '.'."""
    out, current = [], []
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            if not line or line.startswith("#") or line.startswith("@prefix"):
                continue
            if line[0] not in " \t":
                if current:
                    out.append(current)
                current = [line]
            else:
                current.append(line)
                if line.rstrip().endswith("."):
                    out.append(current)
                    current = []
    if current:
        out.append(current)
    return out


def main():
    blocks = blocks_of(SRC)
    by_case = defaultdict(list)
    agents = []
    meta = {}
    case_domain = {}
    for i, b in enumerate(blocks):
        head = b[0]
        if " a eth:Agent" in head:
            agents.append(i)
            continue
        text = "\n".join(b)
        cases = set(m.group(0) for m in CASE_RE.finditer(text))
        if cases:
            meta[i] = cases
            for c in cases:
                by_case[c].append(i)
            if " a eth:EthicalCase" in head:
                m = re.search(r"eth:domain eth:domain_([A-Z]{1,2})", text)
                case_domain[c] = m.group(1) if m else "NA"

    pools = defaultdict(list)
    for cid in sorted(by_case):
        pools[(cid.split("-")[1], case_domain.get(cid, "NA"))].append(cid)
    keys = sorted(pools)
    chosen, round_idx = [], 0
    while len(chosen) < N_CASES:
        progressed = False
        for k in keys:
            if round_idx < len(pools[k]):
                chosen.append(pools[k][round_idx])
                progressed = True
        if not progressed:
            break
        round_idx += 1
    chosen = sorted(chosen)
    chosen_set = set(chosen)
    keep = set(agents)
    for i, cases in meta.items():
        if cases & chosen_set:
            keep.add(i)

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# Stratified slice of fixtures/instances.ttl generated by "
                 "_analysis/ontology/select_instances_subset.py for the G4' validation. "
                 "Every retained block is verbatim; references to dropped individuals "
                 "are left as IRIs.\n")
        fh.write(prefixes())
        for i in sorted(keep):
            fh.write("\n".join(blocks[i]) + "\n")

    report = {
        "generator": "_analysis/ontology/select_instances_subset.py",
        "source": "Ontologias/ontology_v4/fixtures/instances.ttl",
        "cases_total": len(by_case),
        "cases_kept": len(chosen),
        "layers_kept": sorted({c.split("-")[1] for c in chosen}),
        "domains_kept": sorted({case_domain.get(c, "NA") for c in chosen}),
        "blocks_total": len(blocks),
        "blocks_kept": len(keep),
        "agent_blocks_kept": len(agents),
        "chosen_case_ids": chosen,
    }
    with open(STATS, "w") as fh:
        json.dump(report, fh, indent=2)
    print(json.dumps({k: v for k, v in report.items() if k != "chosen_case_ids"}, indent=2))


if __name__ == "__main__":
    main()
