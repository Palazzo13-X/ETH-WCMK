"""Generate ontology v3 (ETH-WCMK) from the canonical Python registry and calibration.

The ontology is generated, not hand-written, so that the TTL is by construction a
mirror of the executable model (gate G6: arithmetic mirror agreement <= 1e-6).
Namespaces are unified: one base namespace `ethwcmk:` for the model, one
`cal:` for calibration individuals, `shacl:` shapes.

Outputs into Ontologias/ontology_v3/:
  01_core.ttl        classes and object properties
  02_facets.ttl      the 28 facet individuals with beta, policy, guard, observable,
                     criticality for all 13 domains
  03_deontic.ttl     NormativeInstrument, Norm, NormConflict, Justification,
                     ProportionalityClaim
  04_agency.ttl      AgentLayer, Agent, DelegationChain, FallbackPolicy, ConfrontationChain
  05_dynamics.ttl    TemporalHorizon, DriftProfile, decision ladder classes
  06_calibration.ttl the fitted calibration individual (mirrors core.Calibration)
  shapes/ontology_shapes.ttl   SHACL shapes
  fixtures/instances.ttl       a worked example case + profile + confrontation

Run:  python3 _analysis/ontology/gen_ontology_v3.py
"""
