def head(title, extra_prefixes=None):
    p = {"ethwcmk": BASE, "cal": CALNS, "fac": FACNS, "inst": INSTNS,
         "rdfs": "http://www.w3.org/2000/01/rdf-syntax-ns#",
         "owl": "http://www.w3.org/2002/07/owl#",
         "xsd": "http://www.w3.org/2001/XMLSchema#",
         "sh": "http://www.w3.org/ns/shacl#"}
    p.update(extra_prefixes or {})
    lines = ["# " + title, "# Generated by _analysis/ontology/gen_ontology_v3.py — do not hand-edit."]
    lines += [f"@prefix {k}: <{v}> ." for k, v in p.items()]
    return "\n".join(lines)


def emit_facets():
    out = [head("02_facets — the 28 canonical facets of ETH-WCMK v11")]
    for f in FACETS:
        out.append(f"\nfac:{f.code} a ethwcmk:Facet ;")
        out.append(f'  ethwcmk:label "{f.label}" ;')
        out.append(f"  ethwcmk:primaryPillar ethwcmk:pillar_{f.primary_pillar()} ;")
        for i, b in enumerate(f.beta):
            out.append(f"  ethwcmk:beta{PILLARS[i]} {b:.6f} ;")
        out.append(f"  ethwcmk:sharedPillars \"{' '.join(p for p, b in zip(PILLARS, f.beta) if b > 0)}\" ;")
        out.append(f"  ethwcmk:nPillars {f.n_pillars()} ;")
        out.append(f"  ethwcmk:aggregationPolicy ethwcmk:policy_{f.policy} ;")
        out.append(f"  ethwcmk:hardGuard {str(f.guard).lower()} ;")
        out.append(f"  ethwcmk:guardMin {f.guard_min:.6f} ;")
        out.append(f"  ethwcmk:weight {f.weight:.6f} ;")
        out.append(f"  ethwcmk:observable \"{f.observable}\" ;")
        out.append(f"  ethwcmk:source \"{f.source}\" ;")
        crit = ", ".join(f"{d}={f.criticality.get(d, 2)}" for d in DOMAINS)
        out.append(f"  ethwcmk:criticalityVector \"{crit}\" .")
    return "\n".join(out)


