def fig6_verdicts():
    cov = json.load(open(os.path.join(R5, "corpus_v7_coverage.json")))
    model = cov["decision_distribution"]
    gold = cov["gold"]["consensus_distribution"]
    order = ["PROHIBIT", "REVIEW_REQUIRED", "ABSTAIN", "ALLOW_WITH_GUARDS", "ALLOW"]
    W, H = 1200, 420
    img, dr = canvas(W, H)
    dr.text((30, 20), "Verdict distribution over 220,400 confrontations: model vs normative panel", fill="#203040", font=font(14, True))
    base = 300
    for k, cls in enumerate(order):
        mv = model.get(cls, 0)
        gv = gold.get(cls, 0)
        mx = 60 + k * 220
        hv = int(mv / 162507 * 200)
        hv2 = int(gv / 162507 * 200)
        dr.rectangle([mx, base - hv, mx + 80, base], fill="#365F91", outline="#203040")
        dr.rectangle([mx + 90, base - hv2, mx + 170, base], fill="#D8B7A6", outline="#203040")
        dr.text((mx, base + 8), cls.replace("_", "\n"), fill="#405060", font=font(11))
        dr.text((mx + 20, base - hv - 18), f"{mv:,}", fill="#203040", font=font(11, True))
        dr.text((mx + 110, base - hv2 - 18), f"{gv:,}", fill="#203040", font=font(11, True))
    dr.text((60, 360), "blue = model; salmon = consensus of the three normative lenses", fill="#405060", font=font(12))
    img.save(os.path.join(OUT, "fig6_verdicts.png"))


