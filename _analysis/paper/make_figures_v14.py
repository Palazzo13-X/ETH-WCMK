def font(size, bold=False):
    cands = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf" if bold else
        "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    ]
    for c in cands:
        if os.path.exists(c):
            return ImageFont.truetype(c, size)
    return ImageFont.load_default()


def canvas(w, h):
    img = Image.new("RGB", (w, h), "white")
    return img, ImageDraw.Draw(img)


def box(d, x, y, w, h, text, fill="#F2F6FA", outline="#4F81BD", size=16, bold=False):
    d.rectangle([x, y, x + w, y + h], fill=fill, outline=outline, width=2)
    f = font(size, bold)
    lines = text.split("\n")
    ty = y + 8
    for ln in lines:
        tw = d.textlength(ln, font=f)
        d.text((x + (w - tw) / 2, ty), ln, fill="#203040", font=f)
        ty += size + 4
    return (x + w // 2, y + h)


def arrow(d, x1, y1, x2, y2, size=14):
    d.line([x1, y1, x2, y2], fill="#4F81BD", width=2)
    d.polygon([(x2 - 6, y2 - 8), (x2 + 6, y2 - 8), (x2, y2)], fill="#4F81BD")


