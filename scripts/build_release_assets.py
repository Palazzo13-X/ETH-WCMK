#!/usr/bin/env python3
"""Build the release assets for a GitHub release (or a Zenodo deposit).

Corpora are deterministic: they are regenerated by the seeded generators in
_analysis/corpus/, so shipping them as compressed assets keeps the repository
small while still giving a reviewer the exact bytes behind every number.

Usage:
    python3 scripts/build_release_assets.py                # all rounds
    python3 scripts/build_release_assets.py --round r5     # one round
    python3 scripts/build_release_assets.py --dry-run

Output: release_assets/<name>.gz  +  release_assets/ASSET_MANIFEST.json
"""
from __future__ import annotations
import argparse
import gzip
import hashlib
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "release_assets")
MIN_BYTES = 1_000_000
PATTERNS = ("Evaluacoes/", "Ontologias/")
SKIP = (".cache_validation", "__pycache__", "manifest")
EXCLUDE = ("instances_subset.ttl",)  # kept in git


def candidates(round_filter: str | None) -> list[str]:
    paths = []
    for root in PATTERNS:
        for dirpath, dirnames, filenames in os.walk(os.path.join(REPO, root)):
            if any(s in dirpath for s in SKIP):
                continue
            for f in filenames:
                if f in EXCLUDE:
                    continue
                p = os.path.join(dirpath, f)
                if os.path.getsize(p) < MIN_BYTES:
                    continue
                if not f.endswith((".jsonl", ".ttl", ".csv", ".json")):
                    continue
                # plain JSON reports stay in git unless they are too big for a clone
                if f.endswith(".json") and os.path.getsize(p) < 10_000_000:
                    continue
                if round_filter and f"/{round_filter}/" not in p:
                    continue
                paths.append(os.path.relpath(p, REPO))
    return sorted(paths)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", help="only this round, e.g. r5")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--level", type=int, default=9)
    args = ap.parse_args()

    paths = candidates(args.round)
    os.makedirs(OUT, exist_ok=True)
    manifest = {"assets": []}
    total_raw = total_gz = 0
    seen: set[str] = set()

    for rel in paths:
        src = os.path.join(REPO, rel)
        name = os.path.basename(rel)
        if name in seen:  # e.g. fixtures/instances.ttl in two ontology versions
            name = rel.replace("/", "_").replace(" ", "-")
        seen.add(name)
        dst = os.path.join(OUT, name + ".gz")
        raw = os.path.getsize(src)
        if args.dry_run:
            with open(src, "rb") as fh:
                gz = len(gzip.compress(fh.read(), args.level))
            print(f"{rel}: {raw/1e6:7.1f} MB -> {gz/1e6:6.2f} MB")
            total_raw += raw
            total_gz += gz
            continue
        with open(src, "rb") as fh, gzip.open(dst, "w", args.level) as out:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                out.write(chunk)
        gz_size = os.path.getsize(dst)
        with open(dst, "rb") as fh:
            h = hashlib.sha256(fh.read()).hexdigest()
        manifest["assets"].append({
            "file": os.path.basename(dst),
            "source": rel,
            "bytes_raw": raw,
            "bytes_gz": gz_size,
            "sha256_gz": h,
        })
        total_raw += raw
        total_gz += gz_size
        print(f"wrote {os.path.basename(dst)} ({gz_size/1e6:.2f} MB)")

    if args.dry_run:
        print(f"TOTAL: {total_raw/1e6:.1f} MB raw -> {total_gz/1e6:.1f} MB gz")
        return 0

    with open(os.path.join(OUT, "ASSET_MANIFEST.json"), "w") as fh:
        json.dump(manifest, fh, indent=2)
    print(f"manifest: {len(manifest['assets'])} assets, {total_gz/1e6:.1f} MB total")
    return 0


if __name__ == "__main__":
    sys.exit(main())
